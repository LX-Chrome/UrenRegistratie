let currentLang = 'nl';
let translatedElements = new WeakMap(); // Cache for already translated elements
let translationTimeout = null;
const TRANSLATION_DEBOUNCE_TIME = 50; // ms to wait before processing multiple DOM changes

function toggleLanguage() {
    currentLang = currentLang === 'nl' ? 'en' : 'nl';
    
    // Clear the translation cache when switching languages
    translatedElements = new WeakMap();
    
    // Perform translation
    translatePage();
    
    // Save language preference
    localStorage.setItem('language', currentLang);
    
    // Update toggle switch visual state
    const languageToggle = document.getElementById('languageToggle');
    if (languageToggle) {
        if (currentLang === 'en') {
            languageToggle.classList.add('active');
        } else {
            languageToggle.classList.remove('active');
        }
    }
    
    // Log for debugging
    console.log('Language switched to:', currentLang);
}

// Helper function to translate a single text
function translateText(text) {
    if (!text || typeof text !== 'string') return text;
    const trimmed = text.trim();
    return translations[currentLang][trimmed] || text;
}

// Process only elements that need translation and haven't been translated yet
function translatePage() {
    // Process data-translate attributes - most specific and reliable
    document.querySelectorAll('[data-translate]:not([data-translated="' + currentLang + '"])').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[currentLang][key]) {
            element.textContent = translations[currentLang][key];
            element.setAttribute('data-translated', currentLang);
        }
    });
    
    // Process data-placeholder attributes
    document.querySelectorAll('[data-placeholder]:not([data-placeholder-translated="' + currentLang + '"])').forEach(element => {
        const key = element.getAttribute('data-placeholder');
        if (translations[currentLang][key]) {
            element.placeholder = translations[currentLang][key];
            element.setAttribute('data-placeholder-translated', currentLang);
        }
    });
    
    // More selective element selection - only translate specific elements that commonly contain text
    const elementsToCheck = document.querySelectorAll(
        'option:not([data-translated]), ' +
        'button:not([data-translated]), ' + 
        'a.btn:not([data-translated]), ' +
        'h1:not([data-translated]), h2:not([data-translated]), h3:not([data-translated]), ' +
        'h4:not([data-translated]), h5:not([data-translated]), h6:not([data-translated]), ' +
        'th:not([data-translated]), ' +
        '.modal-title:not([data-translated]), ' +
        '.modal-body p:not([data-translated])'
    );
    
    elementsToCheck.forEach(element => {
        // Skip elements already translated or with no text
        if (translatedElements.has(element) || !element.textContent.trim()) {
            return;
        }
        
        const text = element.textContent.trim();
        if (translations[currentLang][text]) {
            element.textContent = translations[currentLang][text];
            element.setAttribute('data-translated', currentLang);
            translatedElements.set(element, true);
        }
    });
    
    // Handle greetings separately (complex text)
    document.querySelectorAll('.card-header h5:not([data-greeting-translated="' + currentLang + '"])').forEach(element => {
        const greetingElement = element.querySelector('[data-translate="Goedendag"]');
        if (greetingElement) {
            // Only translate the greeting part (the span element)
            greetingElement.textContent = translations[currentLang]['Goedendag'];
            element.setAttribute('data-greeting-translated', currentLang);
        }
    });
    
    // Handle confirmation dialogs
    if (window.confirm.toString().indexOf('native code') > -1 && !window.confirmTranslated) {
        const originalConfirm = window.confirm;
        window.confirm = function(message) {
            // Translate confirmation messages if they exist in our translations
            if (translations[currentLang][message]) {
                return originalConfirm(translations[currentLang][message]);
            } else {
                return originalConfirm(message);
            }
        };
        window.confirmTranslated = true;
    }
    
    // Re-init Feather icons after translation to ensure they render properly
    if (typeof feather !== 'undefined') {
        feather.replace();
    }
}

// Debounced translation for the MutationObserver
function debouncedTranslate() {
    if (translationTimeout) {
        clearTimeout(translationTimeout);
    }
    
    translationTimeout = setTimeout(() => {
        translatePage();
        translationTimeout = null;
    }, TRANSLATION_DEBOUNCE_TIME);
}

// Preload translations for critical UI elements
