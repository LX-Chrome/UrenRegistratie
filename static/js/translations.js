let currentLang = 'nl';

function toggleLanguage() {
    currentLang = currentLang === 'nl' ? 'en' : 'nl';
    translatePage();
    // Save language preference
    localStorage.setItem('language', currentLang);
    
    // Update toggle switch visual state
    const languageToggle = document.getElementById('languageToggle');
    if (languageToggle) {
        if (currentLang === 'en') {
            languageToggle.classList.add('active');
        } else {
            languageToggle.classList.remove('active');
        }
    }
    
    // Log for debugging
    console.log('Language switched to:', currentLang);
}

function translatePage() {
    // Translate elements with data-translate attribute
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[currentLang][key]) {
            element.textContent = translations[currentLang][key];
        }
    });
    
    // Translate data-placeholder attributes
    document.querySelectorAll('[data-placeholder]').forEach(element => {
        const key = element.getAttribute('data-placeholder');
        if (translations[currentLang][key]) {
            element.placeholder = translations[currentLang][key];
        }
    });
    
    // Translate form elements
    document.querySelectorAll('option, label, input[placeholder], button, a.btn').forEach(element => {
        // Check for option value or text content
        const text = element.textContent.trim();
        if (translations[currentLang][text]) {
            element.textContent = translations[currentLang][text];
        }
        
        // Check for placeholders
        if (element.placeholder && translations[currentLang][element.placeholder]) {
            element.placeholder = translations[currentLang][element.placeholder];
        }
    });
    
    // Translate headers and text in tables
    document.querySelectorAll('h1, h2, h3, h4, h5, h6, th, td, .modal-title, .modal-body').forEach(element => {
        const text = element.textContent.trim();
        if (translations[currentLang][text]) {
            element.textContent = translations[currentLang][text];
        }
    });
    
    // Handle greetings separately (complex text)
    document.querySelectorAll('.card-header h5').forEach(element => {
        const text = element.textContent.trim();
        // Find the span with data-translate="Goedendag" or "Good day"
        const greetingElement = element.querySelector('[data-translate="Goedendag"]');
        if (greetingElement) {
            // Only translate the greeting part (the span element)
            greetingElement.textContent = translations[currentLang]['Goedendag'];
        }
    });
    
    // Handle confirmation dialogs
    if (window.confirm.toString().indexOf('native code') > -1) {
        const originalConfirm = window.confirm;
        window.confirm = function(message) {
            // Translate confirmation messages if they exist in our translations
            if (translations[currentLang][message]) {
                return originalConfirm(translations[currentLang][message]);
            } else {
                return originalConfirm(message);
            }
        };
    }
}

document.addEventListener('DOMContentLoaded', () => {
    // Load saved language preference
    const savedLang = localStorage.getItem('language');
    if (savedLang) {
        currentLang = savedLang;
    }
    
    // Apply translations when page loads
    translatePage();
    
    // Set initial toggle state based on current language
    const languageToggle = document.getElementById('languageToggle');
    if (languageToggle && currentLang === 'en') {
        languageToggle.classList.add('active');
    }
    
    // Also translate when any modal is shown
    document.body.addEventListener('shown.bs.modal', function() {
        translatePage();
    });
});
